function setLocale(loc){
  if(loc!=="en" && loc!=="zh") loc="en";
  const dict = window.I18N[loc];
  document.documentElement.setAttribute("data-locale", loc);
  document.documentElement.setAttribute("lang", loc==="zh"?"zh":"en");
  // text nodes
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const k = el.getAttribute("data-i18n");
    if(dict[k] != null) el.textContent = dict[k];
  });
  // attribute translations (format: key:attr;key:attr)
  document.querySelectorAll("[data-i18n-attr]").forEach(el=>{
    el.getAttribute("data-i18n-attr").split(";").forEach(pair=>{
      const [k,attr] = pair.split(":");
      if(dict[k] != null && attr) el.setAttribute(attr, dict[k]);
    });
  });
  // toggle highlight
  document.querySelectorAll("#lang-switch [data-set-locale]").forEach(s=>{
    s.classList.toggle("on", s.getAttribute("data-set-locale")===loc);
  });
  try{ localStorage.setItem("gc_locale", loc); }catch(e){}
}

document.addEventListener("click", function(e){
  const t = e.target.closest("[data-set-locale]");
  if(!t) return;
  setLocale(t.getAttribute("data-set-locale"));
});

